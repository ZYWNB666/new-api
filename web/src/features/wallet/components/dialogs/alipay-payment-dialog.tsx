import { useQuery } from '@tanstack/react-query'
import { CheckCircle2, ExternalLink } from 'lucide-react'
import { useEffect, useRef, useState } from 'react'
import { useTranslation } from 'react-i18next'

import { Dialog } from '@/components/dialog'
import { LoadingState } from '@/components/loading-state'
import { Button } from '@/components/ui/button'
import { requireServerSuccess } from '@/lib/server-error-message'

import { getAlipayOrderStatus } from '../../api'
import type { AlipayCheckout } from '../../types'

interface AlipayPaymentDialogProps {
  checkout: AlipayCheckout
  onClose: () => void
  onPaid: () => void
}

// The parent keys this component by trade_no so each order owns its timers and query.
export function AlipayPaymentDialog(props: AlipayPaymentDialogProps) {
  const { t } = useTranslation()
  const [timedOut, setTimedOut] = useState(false)
  const notified = useRef(false)
  const query = useQuery({
    queryKey: ['alipay-order', props.checkout.trade_no],
    queryFn: async ({ signal }) => {
      const response = requireServerSuccess(
        await getAlipayOrderStatus(props.checkout.trade_no, signal)
      )
      if (!response.data) throw new Error('Missing payment status')
      return response.data
    },
    refetchInterval: (current) =>
      timedOut ||
      (current.state.data && current.state.data.status !== 'pending')
        ? false
        : 3000,
    refetchIntervalInBackground: false,
    refetchOnWindowFocus: false,
    retry: false,
    gcTime: 0,
    meta: { errorToast: false },
  })
  const paid = query.data?.status === 'success'
  const closed = Boolean(query.data && query.data.status !== 'pending' && !paid)

  useEffect(() => {
    const expiresAt =
      props.checkout.expires_at ?? Math.floor(Date.now() / 1000) + 1800
    const timer = window.setTimeout(
      () => setTimedOut(true),
      Math.max(0, expiresAt * 1000 - Date.now())
    )
    return () => window.clearTimeout(timer)
  }, [props.checkout.expires_at])

  useEffect(() => {
    if (paid && !notified.current) {
      notified.current = true
      props.onPaid()
    }
  }, [paid, props])

  let message = t('Waiting for payment')
  if (paid) {
    message = t('Payment received. Your balance has been updated.')
  } else if (closed) {
    message = t('This order is closed. Check your order history.')
  } else if (timedOut) {
    message = t(
      'Payment waiting period ended. Check your order history before paying again.'
    )
  } else if (query.isError) {
    message = t('Unable to check payment status. Please try again.')
  }

  return (
    <Dialog
      open
      onOpenChange={(open) => {
        if (!open) props.onClose()
      }}
      title={t('Alipay')}
      description={t('Scan with Alipay to complete payment.')}
      contentClassName='max-sm:w-[calc(100vw-1.5rem)] sm:max-w-md'
      bodyClassName='space-y-4'
      footer={
        <>
          {!paid && !closed && (
            <Button
              variant='outline'
              onClick={() => {
                void query.refetch()
              }}
              disabled={query.isFetching}
            >
              {t('Check payment status')}
            </Button>
          )}
          <Button onClick={props.onClose}>{t('Close')}</Button>
        </>
      }
    >
      {!paid &&
        !closed &&
        !timedOut &&
        props.checkout.qr_pay_link && (
          // Alipay is hosted on a fixed, separate origin generated by the backend;
          // it cannot access this document to remove the sandbox. Its checkout
          // needs its own origin for cookies/storage and scripts to render the QR.
          <iframe
            title={t('Alipay payment QR code')}
            src={props.checkout.qr_pay_link}
            className='mx-auto h-72 w-72 max-w-full rounded-lg border bg-white'
            // oxlint-disable-next-line react/iframe-missing-sandbox
            sandbox='allow-scripts allow-forms allow-same-origin'
            referrerPolicy='no-referrer'
          />
        )}
      <div
        role='status'
        className='flex items-center justify-center gap-2 text-center text-sm'
      >
        {paid && (
          <CheckCircle2 aria-hidden className='text-success size-5 shrink-0' />
        )}
        {query.isFetching && !paid && <LoadingState inline size='sm' />}
        <span>{message}</span>
      </div>
      {!paid && !closed && !timedOut && (
        <Button
          variant='link'
          className='h-auto w-full whitespace-normal'
          render={
            <a
              href={props.checkout.pay_link}
              target='_blank'
              rel='noopener noreferrer'
            />
          }
        >
          {t('Open Alipay checkout')}
          <ExternalLink aria-hidden className='size-4 shrink-0' />
        </Button>
      )}
    </Dialog>
  )
}
