// Adaptor relays Jev decision requests to the upstream decision endpoint.
// OpenRouter: https://openrouter.ai/api/alpha/decisions
// TypeSafe official: https://api.typesafe.ai/v1/systemone
type Adaptor struct {
}

func (a *Adaptor) Init(info *relaycommon.RelayInfo) {
}

func (a *Adaptor) GetRequestURL(info *relaycommon.RelayInfo) (string, error) {
	if info.RelayMode != relayconstant.RelayModeJev {
		return "", errors.New("jev channel: only /v1/decisions is supported")
	}
	base := strings.TrimSuffix(info.ChannelBaseUrl, "/")
	if strings.Contains(base, "typesafe.ai") {
		return fmt.Sprintf("%s/v1/systemone", base), nil
	}
	return fmt.Sprintf("%s/alpha/decisions", base), nil
}

func (a *Adaptor) SetupRequestHeader(c *gin.Context, req *http.Header, info *relaycommon.RelayInfo) error {
	channel.SetupApiRequestHeader(info, c, req)
	req.Set("Authorization", "Bearer "+info.ApiKey)
	return nil
}

